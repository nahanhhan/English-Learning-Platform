def band_for_score(score):
    if score >= 13:
        return '13-15分档'
    if score >= 10:
        return '10-12分档'
    if score >= 7:
        return '7-9分档'
    if score >= 4:
        return '4-6分档'
    return '1-3分档' if score > 0 else '0分'


def require_score_reason(result):
    reason = result.get('score_reason')
    if not isinstance(reason, str) or not reason.strip():
        from .ai_client import AiError
        raise AiError('批改缺少整体评分依据，作答已保留，请重新批改')
    return reason.strip()


